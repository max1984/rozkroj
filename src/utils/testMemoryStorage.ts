/**
 * Node's built-in `localStorage` global needs --localstorage-file to actually
 * persist anything (and shadows jsdom's implementation when that's used
 * instead), so tests stub global.localStorage with this in-memory Storage
 * implementation rather than relying on a DOM test environment.
 */
export class MemoryStorage implements Storage {
  private store = new Map<string, string>();
  get length(): number {
    return this.store.size;
  }
  clear(): void {
    this.store.clear();
  }
  getItem(key: string): string | null {
    return this.store.has(key) ? this.store.get(key)! : null;
  }
  key(index: number): string | null {
    return Array.from(this.store.keys())[index] ?? null;
  }
  removeItem(key: string): void {
    this.store.delete(key);
  }
  setItem(key: string, value: string): void {
    this.store.set(key, String(value));
  }
}
